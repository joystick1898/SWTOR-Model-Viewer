import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {convert,defaultState} from '../src/backend.mjs';
import {writeExportBundle} from '../src/export-bundle.mjs';
const catalog=JSON.parse(await fs.readFile('output/equipment/catalog.json','utf8'));
const item=catalog.items.find(r=>r.models.some(m=>m.endsWith('/saber_unstable_vented_a01_v01.gr2')));
assert(item);
const state={...defaultState,clip:'cb_warrior_saber_idle_1.jba',equipment:[{item:item.id,bone:'RightWeapon',blade:{enabled:true,effect:'native',motion:'animated',frame:4,core:'#ffffff',glow:'#a04cff',length:90,width:2,intensity:1.5}}]};
const preview=await convert(state,'preview',console.log);
const fx=preview.materialDetails.filter(m=>m.family==='SaberFX');assert(fx.some(m=>m.saberFX.fps>0));
assert(preview.parts.some(p=>p.name.includes('dummy_vent_blade_02_loc')));
assert(fx.every(m=>!/trail|turn_on|turn_off|impact/i.test(m.sourceParticle)));
const exported=await convert(state,'fbx',console.log);
const folder=path.resolve('output/persistent-sabers');
const manifest=await writeExportBundle(exported,state,path.join(folder,'Character.fbx'));
await fs.copyFile(preview.file,path.join(folder,'character.glb'));
await fs.writeFile(path.join(folder,'character-preview.json'),JSON.stringify(preview,null,2));
assert(manifest.materials.some(m=>m.saberFX?.animated));
await fs.writeFile(path.join(folder,'pipeline-check.json'),JSON.stringify({ok:true,preview:preview.file,fbx:exported.file,fxMaterials:fx.length,secondNativeVent:true,persistentOnly:true},null,2));
console.log('PERSISTENT_SABER_PIPELINE_PASS');
