import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {convert,defaultState,validateState} from '../src/backend.mjs';
import {writeExportBundle} from '../src/export-bundle.mjs';
const state=validateState({...defaultState,time:.52,weapon:'blaster_high02_a03',appearance:{body:'bfn',head:3,hair:12,hairColor:'#482D18',eyeColor:'#588099',skinBrightness:.2,gearColor:'#8040C0'}});
const result=await convert(state,'fbx',console.log);
const file=path.resolve('output/examples/Human-female-custom.fbx');
const manifest=await writeExportBundle(result,state,file);
assert(result.rigged&&result.boneCount>=140);
assert.equal(manifest.materials.find(m=>m.family==='HairC').alphaCutoff,.75);
assert.deepEqual(manifest.preset,validateState(JSON.parse(JSON.stringify(state))));
await fs.writeFile('output/examples/Human-female-custom.pose.json',JSON.stringify(state,null,2));
await fs.writeFile('reports/designer-export-smoke.json',JSON.stringify({ok:true,file,result},null,2));
console.log('PASS: customized female rigged FBX and appearance preset');
const hairState=validateState({...defaultState,time:1.89,clip:'am_env_idle_hot_02.jba',weapon:'blaster_high02_a03',appearance:{body:'bfn',hair:5}});
const hairResult=await convert(hairState,'fbx',console.log);
assert.equal(hairResult.secondaryAttachments.length,2);
const hairFile=path.resolve('output/examples/Human-female-hair-fixed.fbx');
await writeExportBundle(hairResult,hairState,hairFile);
await fs.writeFile('reports/hair-export-smoke.json',JSON.stringify({ok:true,file:hairFile,result:hairResult},null,2));
console.log('PASS: anchored hair in the reported idle pose exports with skeleton');
