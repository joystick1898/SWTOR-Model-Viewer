import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {importNpcDesigner} from '../src/designer.mjs';
import {convert,defaultState,validateState} from '../src/backend.mjs';
import {resolveEquipment} from '../src/equipment.mjs';
import {writeExportBundle} from '../src/export-bundle.mjs';
const imported=await importNpcDesigner('16141108995265840656-0');
const base={...defaultState,version:2,character:'native-designer',designer:imported.designer,clip:null};
const original=await convert(base,'preview');assert.equal(original.duration,0);
const shoulder=original.parts.find(p=>p.source?.includes('_shld.gr2')).source;
const item='467aaf4e2ef3f5face348c1c';
const record=(await resolveEquipment([{item,bone:'@skin'}]))[0];
const component=record.modelTemplates.find(p=>p.includes('_collar.gr2'));assert(component);
const equipment=[{item,bone:'@skin',replaceSlot:false,components:[component],colors:{[component]:{primary:'#2C72C4',secondary:'#CE3030'}}}];
const edited={...base,equipment,designer:{...base.designer,colors:{[shoulder]:{primary:'#218134',secondary:'#EEBB34'}}}};
const preview=await convert(edited,'preview');
assert.equal(preview.parts.filter(p=>p.equipmentLayer===0).length,1);
assert.equal(preview.parts.filter(p=>p.slot==='chest').length,original.parts.filter(p=>p.slot==='chest').length);
assert(preview.equipmentComponents[item].includes(component));
const originalBases=new Set(original.materialDetails.map(m=>m.textures.base));
assert(preview.materialDetails.some(m=>!originalBases.has(m.textures.base)));assert(preview.materialDetails.some(m=>originalBases.has(m.textures.base)));
const saved=validateState(JSON.parse(JSON.stringify(preview.state)));assert.deepEqual(saved.designer,preview.state.designer);assert.equal(saved.equipment[0].replaceSlot,false);assert.deepEqual(saved.equipment[0].components,[component]);
const exported=await convert(saved,'fbx');const destination=path.resolve('output/designer-validation/Admiral-independent-pieces.fbx');await writeExportBundle(exported,saved,destination);
const report=JSON.parse(await fs.readFile('reports/designer-pipeline-smoke.json','utf8'));
report.results=report.results.filter(r=>r.id!=='admiral-independent-pieces');report.results.push({id:'admiral-independent-pieces',ok:true,preview:preview.file,exported,destination});await fs.writeFile('reports/designer-pipeline-smoke.json',JSON.stringify(report,null,2));
await fs.writeFile('reports/designer-pieces-smoke.json',JSON.stringify({ok:true,restPose:true,presetRoundTrip:true,baseClothingPreserved:true,independentDyes:true,component,equipment:preview.state.equipment},null,2));
console.log('PASS native rest pose, single component layering, independent dyes, save/load and FBX');
